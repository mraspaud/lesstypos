"""Generate data/<lang>.words.js from wordfreq.

Usage: python tools/make_wordlist.py en 30000
Requires: pip install wordfreq english-words

Word frequencies: wordfreq by Robyn Speer, data CC-BY-SA 4.0
(https://github.com/rspeer/wordfreq). The generated list is therefore
distributed under CC-BY-SA 4.0.
Proper-noun filtering (English only) uses the english-words package
(web2 + gcide lists): a word is dropped if the dictionaries know it only
capitalised. Unknown short words (<= 3 letters) are dropped as likely acronyms.
"""
import json
import sys

from wordfreq import top_n_list, zipf_frequency

PROFANITY = {
    "fuck", "fucking", "fucked", "fucker", "fucks", "shit", "shitty", "bitch",
    "bitches", "cunt", "dick", "dicks", "cock", "cocks", "pussy", "porn",
    "porno", "nigga", "nigger", "niggas", "fag", "faggot", "slut", "whore",
    "asshole", "bastard", "motherfucker", "tits", "boobs", "dildo", "rape",
    "raped", "rapist", "retard", "retarded", "wank", "wanker", "twat", "cum",
}


def is_word(w):
    core = w.replace("'", "")
    return core.isalpha() and w == w.lower() and not w.startswith("'") and not w.endswith("'")


def main(lang="en", n=30000):
    n = int(n)
    words = [w for w in top_n_list(lang, int(n * 1.6)) if is_word(w) and w not in PROFANITY]
    if lang == "en":
        from english_words import get_english_words_set as g
        d = g(["web2"], lower=False) | g(["gcide"], lower=False)
        low = {w for w in d if w.islower()}
        cap = {w.lower() for w in d if w[:1].isupper()}

        def keep(w):
            base = w.split("'")[0]
            if w in low or base in low:
                return True
            if base in cap:
                return False
            return len(base) > 3

        words = [w for w in words if keep(w) or w in ("i",)]
    words = words[:n]
    zipf = [round(zipf_frequency(w, lang), 2) for w in words]
    out = f"data/{lang}.words.js"
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/make_wordlist.py. Do not edit.\n")
        f.write("// Source: wordfreq (Robyn Speer et al.), CC-BY-SA 4.0. This file: CC-BY-SA 4.0.\n")
        f.write("(function (g) { var FT = g.FT = g.FT || {}; FT.data = FT.data || {};\n")
        f.write(f"FT.data[{json.dumps(lang)}] = {{ words: {json.dumps(' '.join(words))},\n")
        f.write(f"  zipf: {json.dumps(zipf, separators=(',', ':'))} }};\n")
        f.write("})(typeof window !== 'undefined' ? window : globalThis);\n")
    print(out, len(words))


if __name__ == "__main__":
    main(*sys.argv[1:])
