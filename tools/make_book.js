// Writes data/alice.js, the book that comes with the app, from a Project
// Gutenberg EPUB of Alice's Adventures in Wonderland (public domain), using
// the app's own extractor. Only the title, author, chapter titles, words and
// paragraph ends are kept: no Project Gutenberg text or trademark remains.
// Run: node tools/make_book.js path/to/pg11.epub
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { load, ROOT } = require('../test/helpers/load');

async function main(epubPath) {
  const FT = load({ skip: ['data/alice.js'] });
  const book = await FT.books.fromEpub(new Uint8Array(fs.readFileSync(epubPath)));
  const words = book.chapters.flatMap((c) => c.words).join(' ');
  if (/gutenberg/i.test(words)) throw new Error('Project Gutenberg text left in the book');
  const data = {
    title: book.title.replace(/'/g, '’'),
    author: book.author,
    start: book.start,
    chapters: book.chapters.map((c) => ({ title: c.title, text: c.words.join(' '), breaks: c.breaks })),
  };
  const out = '// Generated by tools/make_book.js. Do not edit.\n' +
    '// Lewis Carroll, Alice’s Adventures in Wonderland (1865). Public domain.\n' +
    '(function (g) { var FT = g.FT = g.FT || {}; FT.data = FT.data || {};\n' +
    'FT.data.alice = ' + JSON.stringify(data) + ';\n})(globalThis);\n';
  fs.writeFileSync(path.join(ROOT, 'data', 'alice.js'), out);
  console.log(data.title, '·', data.chapters.length, 'chapters ·', Math.round(out.length / 1024), 'KB');
}

main(process.argv[2]).catch((e) => { console.error(e.message); process.exit(1); });
